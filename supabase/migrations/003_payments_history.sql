create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id bigint null,
  full_name text null,
  username text null,
  series_name text null,
  date timestamptz not null default now()
);

alter table public.payments
  add column if not exists payment_order_id uuid references public.payment_orders(id) on delete set null;

create unique index if not exists payments_payment_order_id_unique
  on public.payments(payment_order_id);

create index if not exists payments_user_date_idx
  on public.payments(user_id, date desc);
